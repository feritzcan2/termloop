import { rustEmitter, formatRust } from "./emit-rust.mjs";
import { typeScriptEmitter } from "./emit-typescript.mjs";

// The local PM daemon's control contract. It has no MCP-only tools (the PM
// agent tools come from modules/pm) and one capability scope.
export const pmTarget = {
  name: "pm",
  schemaPath: "contract/schema/control.pm.schema.json",
  extraSchemas: [],
  rustOutDir: "contract/generated/pm-rust/src",
  tsOutDir: "contract/generated/pm-typescript/src",
  render: renderPm,
};

const LONG_RUNNING_METHODS = ["pm_jira_pull", "pm_jira_diff_read", "pm_jira_apply", "pm_jira_projects_read", "pm_jira_statuses_read", "pm_jira_favourite_filters_read", "pm_jira_search", "pm_jira_boards_read", "pm_jira_sprints_read", "pm_jira_sprint_import", "pm_agent_launch", "pm_check_start", "pm_skill_run", "pm_skill_creator_launch", "pm_skill_draft_dry_run"];

function renderPm(model) {
  const rust = rustEmitter(model);
  const ts = typeScriptEmitter(model);
  const { identity, methods, events } = model;
  const fullMethods = model.capabilityScopes["pm.full"];
  if (JSON.stringify(fullMethods) !== JSON.stringify(methods)) {
    throw new Error("pm.full must list every PM method in method enum order");
  }
  if (model.mcpTools.length) throw new Error("the PM control schema has no MCP-only tools");
  for (const method of LONG_RUNNING_METHODS) {
    if (!methods.includes(method)) throw new Error(`unknown long-running PM method: ${method}`);
  }

  const rustSource = formatRust(`// @generated by tools/codegen/generate.mjs; do not edit.
${rust.prelude()}

pub const CONTRACT_IDENTITY: &str = ${JSON.stringify(identity)};
pub const CAPABILITY_SCOPE: &str = "pm.full";
pub const METHODS: &[&str] = &[
${rust.stringList(methods)}
];
pub const EVENTS: &[&str] = &[
${rust.stringList(events)}
];

${rust.definitions()}

${rust.methodAliases()}

${rust.constraintHelpers()}

${rust.methodAndEventValidators()}
`);

  const tsSource = `// @generated by tools/codegen/generate.mjs; do not edit.
export const CONTRACT_IDENTITY = ${JSON.stringify(identity)} as const;
export const CAPABILITY_SCOPE = "pm.full" as const;
export const METHODS = ${JSON.stringify(methods)} as const;
export const EVENTS = ${JSON.stringify(events)} as const;
export type Method = typeof METHODS[number];

${ts.definitions()}

${ts.methodAliases()}

${ts.methodMaps()}
const PM_REQUEST_TIMEOUT_MS = 12_000;
const PM_LONG_RUNNING_REQUEST_TIMEOUT_MS = 300_000;
const PM_LONG_RUNNING_METHODS: readonly Method[] = ${JSON.stringify(LONG_RUNNING_METHODS)};
export function pmRequestTimeoutMs(method: Method): number {
  // Jira and agent launches wait on bounded provider and process work.
  return PM_LONG_RUNNING_METHODS.includes(method) ? PM_LONG_RUNNING_REQUEST_TIMEOUT_MS : PM_REQUEST_TIMEOUT_MS;
}
${ts.validators()}

${ts.client({
  clientName: "TermLoopPmClient",
  errorName: "TermLoopPmError",
  timeoutFunction: "pmRequestTimeoutMs",
  cancelMethod: "pm_cancel",
  conveniences: [["version", "pm_system_version"]],
})}`;

  return [
    [`${pmTarget.rustOutDir}/lib.rs`, "// @generated by tools/codegen/generate.mjs; do not edit.\npub mod pm;\n"],
    [`${pmTarget.rustOutDir}/pm.rs`, rustSource],
    [`${pmTarget.tsOutDir}/pm.ts`, tsSource],
  ];
}
