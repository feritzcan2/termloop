import { rustEmitter, formatRust } from "./emit-rust.mjs";
import { typeScriptEmitter } from "./emit-typescript.mjs";
import { definitionName, dereferenceLocalSchema, referenceKey } from "./model.mjs";

// The developer daemon's current control contract, with its MCP-only tools and
// the access-plane identity.
export const controlTarget = {
  name: "control",
  schemaPath: "contract/schema/control.current.schema.json",
  extraSchemas: [
    { owner: "MCP", path: "contract/schema/mcp.ask-to.schema.json" },
    { owner: "access", role: "access", path: "contract/schema/access.v1.schema.json" },
  ],
  rustOutDir: "contract/generated/rust/src",
  tsOutDir: "contract/generated/typescript/src",
  render: renderControl,
};

function renderControl(model) {
  const rust = rustEmitter(model);
  const ts = typeScriptEmitter(model);
  const { identity, accessIdentity, methods, events, mcpTools, mcpToolShapes } = model;
  const readOnlyMethods = model.capabilityScopes["control.readOnly"];
  const companionMethods = model.capabilityScopes["control.companion"];
  const mcpInteractiveTools = model.toolsForMcpRole("interactive");
  const mcpStewardTools = model.toolsForMcpRole("steward");
  const mcpHelperTools = model.toolsForMcpRole("helper");
  const mcpPlaybookEvaluatorTools = model.toolsForMcpRole("playbookEvaluator");
  const mcpImproverTools = model.toolsForMcpRole("improver");
  const mcpAgentCreatorTools = model.toolsForMcpRole("agentCreator");
  const mcpToolDefinitions = mcpTools.map((name) => ({
    name,
    description: mcpToolShapes[name].description,
    inputSchema: dereferenceLocalSchema(model, mcpToolShapes[name].params),
    annotations: mcpToolShapes[name].annotations,
  }));
  const toolDto = (tool, side) => definitionName(model, referenceKey(mcpToolShapes[tool][side].$ref));

  const rustSource = formatRust(`// @generated by tools/codegen/generate.mjs; do not edit.
${rust.prelude()}

pub const CONTRACT_IDENTITY: &str = ${JSON.stringify(identity)};
pub const ACCESS_PROTOCOL_IDENTITY: &str = ${JSON.stringify(accessIdentity)};
pub const METHODS: &[&str] = &[
${rust.stringList(methods)}
];
pub const READ_ONLY_METHODS: &[&str] = &[
${rust.stringList(readOnlyMethods)}
];
pub const COMPANION_METHODS: &[&str] = &[
${rust.stringList(companionMethods)}
];
pub const EVENTS: &[&str] = &[
${rust.stringList(events)}
];
pub const MCP_TOOLS: &[&str] = &[
${rust.stringList(mcpTools)}
];
pub const MCP_INTERACTIVE_TOOLS: &[&str] = &[
${rust.stringList(mcpInteractiveTools)}
];
pub const MCP_STEWARD_TOOLS: &[&str] = &[
${rust.stringList(mcpStewardTools)}
];
pub const MCP_HELPER_TOOLS: &[&str] = &[
${rust.stringList(mcpHelperTools)}
];
pub const MCP_PLAYBOOK_EVALUATOR_TOOLS: &[&str] = &[
${rust.stringList(mcpPlaybookEvaluatorTools)}
];
pub const MCP_AGENT_CREATOR_TOOLS: &[&str] = &[
${rust.stringList(mcpAgentCreatorTools)}
];

pub const MCP_IMPROVER_TOOLS: &[&str] = &[
${rust.stringList(mcpImproverTools)}
];
pub const MCP_TOOL_DEFINITIONS_JSON: &str = ${JSON.stringify(JSON.stringify(mcpToolDefinitions))};

${rust.definitions()}

${rust.methodAliases()}

${rust.constraintHelpers()}

${rust.methodAndEventValidators()}

#[allow(clippy::absurd_extreme_comparisons, clippy::len_zero, clippy::redundant_closure)]
pub fn validate_mcp_tool_params(tool: &str, params: &Value) -> bool {
    match tool {
${mcpTools.map((tool) => `        ${JSON.stringify(tool)} => serde_json::from_value::<${toolDto(tool, "params")}>(params.clone()).is_ok() && ${rust.constraint(mcpToolShapes[tool].params, "params")},`).join("\n")}
        _ => false,
    }
}

#[allow(clippy::absurd_extreme_comparisons, clippy::len_zero, clippy::redundant_closure)]
pub fn validate_mcp_tool_result(tool: &str, result: &Value) -> bool {
    match tool {
${mcpTools.map((tool) => `        ${JSON.stringify(tool)} => serde_json::from_value::<${toolDto(tool, "result")}>(result.clone()).is_ok() && ${rust.constraint(mcpToolShapes[tool].result, "result")},`).join("\n")}
        _ => false,
    }
}
`);

  const tsSource = `// @generated by tools/codegen/generate.mjs; do not edit.
export const CONTRACT_IDENTITY = ${JSON.stringify(identity)} as const;
export const ACCESS_PROTOCOL_IDENTITY = ${JSON.stringify(accessIdentity)} as const;
export const METHODS = ${JSON.stringify(methods)} as const;
export const READ_ONLY_METHODS = ${JSON.stringify(readOnlyMethods)} as const;
export const COMPANION_METHODS = ${JSON.stringify(companionMethods)} as const;
export const EVENTS = ${JSON.stringify(events)} as const;
export const MCP_TOOLS = ${JSON.stringify(mcpTools)} as const;
export const MCP_INTERACTIVE_TOOLS = ${JSON.stringify(mcpInteractiveTools)} as const;
export const MCP_STEWARD_TOOLS = ${JSON.stringify(mcpStewardTools)} as const;
export const MCP_PLAYBOOK_EVALUATOR_TOOLS = ${JSON.stringify(mcpPlaybookEvaluatorTools)} as const;
export const MCP_HELPER_TOOLS = ${JSON.stringify(mcpHelperTools)} as const;
export const MCP_AGENT_CREATOR_TOOLS = ${JSON.stringify(mcpAgentCreatorTools)} as const;
export const MCP_IMPROVER_TOOLS = ${JSON.stringify(mcpImproverTools)} as const;
export const MCP_TOOL_DEFINITIONS = ${JSON.stringify(mcpToolDefinitions)} as const;
export type Method = typeof METHODS[number];

${ts.definitions()}

${ts.methodAliases()}

${ts.methodMaps()}
const CONTROL_REQUEST_TIMEOUT_MS = 12_000;
const LONG_RUNNING_REQUEST_TIMEOUT_MS = 300_000;
export function controlRequestTimeoutMs(method: Method): number {
  // Two account probes can each take 5s for version and 8s for auth, plus transport.
  if (method === "agent.authStatusList") return 45_000;
  return method === "task.cleanupWorktree" || method === "task.discardStaleWorktree" || method === "session.relocateAgentToTask" || method === "session.relocateAgentToProject" || method === "taskSource.boardList" || method === "taskSource.boardListStored" || method === "taskSource.statusList" || method === "taskSource.statusListStored" || method === "taskSource.refresh" || method === "playbook.update"
    ? LONG_RUNNING_REQUEST_TIMEOUT_MS
    : CONTROL_REQUEST_TIMEOUT_MS;
}
${ts.validators()}

export function validateMcpToolResult(tool: string, result: unknown): boolean {
  switch (tool) {
${mcpTools.map((tool) => `    case ${JSON.stringify(tool)}: return ${ts.constraint(mcpToolShapes[tool].result, "result")};`).join("\n")}
    default: return false;
  }
}

${ts.client({
  clientName: "TermLoopControlClient",
  errorName: "TermLoopControlError",
  timeoutFunction: "controlRequestTimeoutMs",
  cancelMethod: "control.cancel",
  conveniences: [["version", "system.version"], ["capabilities", "system.capabilities"], ["ping", "system.ping"]],
})}`;

  return [
    [`${controlTarget.rustOutDir}/lib.rs`, "// @generated by tools/codegen/generate.mjs; do not edit.\npub mod current;\n"],
    [`${controlTarget.rustOutDir}/current.rs`, rustSource],
    [`${controlTarget.tsOutDir}/current.ts`, tsSource],
  ];
}
